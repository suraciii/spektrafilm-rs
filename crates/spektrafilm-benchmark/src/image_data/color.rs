pub(crate) fn norm_space(s: &str) -> String {
    let k = s
        .to_ascii_lowercase()
        .replace(['-', '_', ' ', '(', ')'], "");
    match k.as_str() {
        "srgb" => "sRGB",
        "adobergb1998" | "adobergb" => "Adobe RGB (1998)",
        "prophotorgb" | "prophoto" => "ProPhoto RGB",
        "displayp3" | "p3" => "Display P3",
        "dcip3" => "DCI-P3",
        "iturbt2020" | "rec2020" | "bt2020" => "ITU-R BT.2020",
        "acescg" => "ACEScg",
        "aces2065" | "aces20651" => "ACES2065-1",
        _ => s,
    }
    .to_owned()
}
pub(crate) fn norm_transfer(v: &Value) -> String {
    if let Some(b) = v.as_bool() {
        return if b { "encoded" } else { "linear" }.to_owned();
    }
    let s = match v.as_str() {
        Some(x) => x,
        None => return String::new(),
    };
    let k = s.to_ascii_lowercase().replace(['-', '_', ' ', '"'], "");
    match k.as_str() {
        "srgb" => "srgb",
        "encoded" | "true" | "cctfencoded" => "encoded",
        "linear" | "identity" | "false" => "linear",
        _ => s,
    }
    .to_owned()
}
pub(crate) fn srgb_decode(x: f64) -> f64 {
    if x <= 0.04045 {
        x / 12.92
    } else {
        ((x.max(0.04045) + 0.055) / 1.055).powf(2.4)
    }
}
pub(crate) fn srgb_encode(x: f64) -> f64 {
    if x <= 0.0031308 {
        x * 12.92
    } else {
        1.055 * x.max(0.0031308).powf(1.0 / 2.4) - 0.055
    }
}
pub(crate) fn decode(space: &str, x: f64) -> f64 {
    match space {
        "sRGB" | "Display P3" => srgb_decode(x),
        "DCI-P3" => x.powf(2.6),
        "Adobe RGB (1998)" => x.powf(2.19921875),
        "ProPhoto RGB" => {
            if x < 16.0 / 512.0 {
                x / 16.0
            } else {
                x.powf(1.8)
            }
        }
        "ITU-R BT.2020" => {
            let a = 1.099;
            let b = 0.018_f64;
            let threshold = a * b.powf(0.45) - (a - 1.);
            if x < threshold {
                x / 4.5
            } else {
                ((x + a - 1.0) / a).powf(1.0 / 0.45)
            }
        }
        _ => x,
    }
}
pub(crate) fn mul(m: [[f64; 3]; 3], v: [f64; 3]) -> [f64; 3] {
    [
        m[0][0] * v[0] + m[0][1] * v[1] + m[0][2] * v[2],
        m[1][0] * v[0] + m[1][1] * v[1] + m[1][2] * v[2],
        m[2][0] * v[0] + m[2][1] * v[1] + m[2][2] * v[2],
    ]
}
pub(crate) fn inv(m: [[f64; 3]; 3]) -> [[f64; 3]; 3] {
    let d = m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1])
        - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
        + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]);
    [
        [
            (m[1][1] * m[2][2] - m[1][2] * m[2][1]) / d,
            (m[0][2] * m[2][1] - m[0][1] * m[2][2]) / d,
            (m[0][1] * m[1][2] - m[0][2] * m[1][1]) / d,
        ],
        [
            (m[1][2] * m[2][0] - m[1][0] * m[2][2]) / d,
            (m[0][0] * m[2][2] - m[0][2] * m[2][0]) / d,
            (m[0][2] * m[1][0] - m[0][0] * m[1][2]) / d,
        ],
        [
            (m[1][0] * m[2][1] - m[1][1] * m[2][0]) / d,
            (m[0][1] * m[2][0] - m[0][0] * m[2][1]) / d,
            (m[0][0] * m[1][1] - m[0][1] * m[1][0]) / d,
        ],
    ]
}

pub(crate) fn cat02(a: [f64; 2], b: [f64; 2]) -> [[f64; 3]; 3] {
    let xyz = |p: [f64; 2]| [p[0] / p[1], 1., (1. - p[0] - p[1]) / p[1]];
    let l = [
        [0.7328, 0.4296, -0.1624],
        [-0.7036, 1.6975, 0.0061],
        [0.003, 0.0136, 0.9834],
    ];
    let li = inv(l);
    let x = mul(l, xyz(a));
    let y = mul(l, xyz(b));
    let mut o = [[0.; 3]; 3];
    for i in 0..3 {
        for j in 0..3 {
            for k in 0..3 {
                o[i][j] += li[i][k] * (y[k] / x[k]) * l[k][j];
            }
        }
    }
    o
}
pub(crate) fn to_srgb_linear(v: [f64; 3], s: &str) -> Option<[f64; 3]> {
    let (m, w) = space_matrix(s);
    if m[0][0] == 0. {
        return None;
    }
    let xyz = mul(m, v);
    Some(mul(
        [
            [3.2406, -1.5372, -0.4986],
            [-0.9689, 1.8758, 0.0415],
            [0.0557, -0.204, 1.057],
        ],
        mul(cat02(w, [0.3127, 0.329]), xyz),
    ))
}
